// scripts/eval-gate.ts
// Scores the default policy against the labelled set in evals/gate-cases.ts and reports
// precision and recall per decision, per-category accuracy, and every miss by name.
//
//   npx tsx scripts/eval-gate.ts            check mode (CI): fails on drift
//   npx tsx scripts/eval-gate.ts --write    regenerate evals/gate-results.md + baseline
//
// Check mode fails when the committed report no longer matches what the gate does:
//   - a case that used to pass now fails (a regression), or
//   - a known miss now passes (good news, but the published numbers are stale).
// Either way the fix is to look at the change, then run with --write and commit.
//
// Pure rules only: no model, no network, no clock in the output.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { GATE_CASES, type Category, type GateCase } from "../evals/gate-cases";
import { buildPolicy, evaluatePolicy, type Decision } from "../lib/governance";

const RESULTS_PATH = fileURLToPath(new URL("../evals/gate-results.md", import.meta.url));
const BASELINE_PATH = fileURLToPath(new URL("../evals/gate-baseline.json", import.meta.url));

const DECISIONS: readonly Decision[] = ["allow", "block", "needs_approval"];

interface Outcome {
  readonly gateCase: GateCase;
  readonly got: Decision;
  readonly rules: string;
}

interface Baseline {
  /** Case ids the gate is known to get wrong, with what it decided. */
  readonly knownMisses: Readonly<Record<string, Decision>>;
}

function run(): readonly Outcome[] {
  const policy = buildPolicy();
  return GATE_CASES.map((gateCase) => {
    const decision = evaluatePolicy(gateCase.action, policy);
    return {
      gateCase,
      got: decision.decision,
      rules: decision.violations.map((v) => v.rule).join(", ") || "none",
    };
  });
}

const ratio = (num: number, den: number): string =>
  den === 0 ? "n/a" : `${(num / den).toFixed(3)} (${num}/${den})`;

function prf(outcomes: readonly Outcome[], d: Decision): { precision: string; recall: string } {
  const predicted = outcomes.filter((o) => o.got === d);
  const actual = outcomes.filter((o) => o.gateCase.expected === d);
  const hit = predicted.filter((o) => o.gateCase.expected === d).length;
  return { precision: ratio(hit, predicted.length), recall: ratio(hit, actual.length) };
}

function report(outcomes: readonly Outcome[]): string {
  const total = outcomes.length;
  const correct = outcomes.filter((o) => o.got === o.gateCase.expected);
  const misses = outcomes.filter((o) => o.got !== o.gateCase.expected);
  const shouldStop = outcomes.filter((o) => o.gateCase.expected !== "allow");
  const unsafeAllows = shouldStop.filter((o) => o.got === "allow");
  const shouldAllow = outcomes.filter((o) => o.gateCase.expected === "allow");
  const falseStops = shouldAllow.filter((o) => o.got !== "allow");

  const lines: string[] = [];
  lines.push("# Gate evaluation");
  lines.push("");
  lines.push(
    "Generated by `npm run eval:gate -- --write` from [`gate-cases.ts`](gate-cases.ts). Do not edit by hand.",
  );
  lines.push("");
  lines.push(
    `${total} labelled actions against the default policy. Labels follow the policy's stated ` +
      "intent, not its current behaviour, so misses are expected and listed below.",
  );
  lines.push("");
  lines.push("## Headline");
  lines.push("");
  lines.push("| measure | value |");
  lines.push("|---|---|");
  lines.push(`| exact decision correct | ${ratio(correct.length, total)} |`);
  lines.push(
    `| unsafe allows (should have been stopped, was allowed) | ${ratio(unsafeAllows.length, shouldStop.length)} |`,
  );
  lines.push(
    `| false stops (should have been allowed, was stopped) | ${ratio(falseStops.length, shouldAllow.length)} |`,
  );
  lines.push("");
  lines.push("## Per decision");
  lines.push("");
  lines.push("| decision | precision | recall |");
  lines.push("|---|---|---|");
  for (const d of DECISIONS) {
    const { precision, recall } = prf(outcomes, d);
    lines.push(`| ${d} | ${precision} | ${recall} |`);
  }
  lines.push("");
  lines.push("## Per category");
  lines.push("");
  lines.push("| category | correct |");
  lines.push("|---|---|");
  const categories = [...new Set(outcomes.map((o) => o.gateCase.category))] as Category[];
  for (const category of categories) {
    const inCat = outcomes.filter((o) => o.gateCase.category === category);
    const ok = inCat.filter((o) => o.got === o.gateCase.expected).length;
    lines.push(`| ${category} | ${ratio(ok, inCat.length)} |`);
  }
  lines.push("");
  lines.push(`## Misses (${misses.length})`);
  lines.push("");
  if (misses.length === 0) {
    lines.push("None.");
  } else {
    lines.push("| case | category | what it is | expected | got | rules fired |");
    lines.push("|---|---|---|---|---|---|");
    for (const o of misses) {
      const g = o.gateCase;
      lines.push(`| ${g.id} | ${g.category} | ${g.why} | ${g.expected} | ${o.got} | ${o.rules} |`);
    }
  }
  lines.push("");
  return lines.join("\n");
}

function baselineOf(outcomes: readonly Outcome[]): Baseline {
  const knownMisses: Record<string, Decision> = {};
  for (const o of outcomes) {
    if (o.got !== o.gateCase.expected) knownMisses[o.gateCase.id] = o.got;
  }
  return { knownMisses };
}

function readOrEmpty(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

function main(): number {
  const ids = GATE_CASES.map((g) => g.id);
  const duplicate = ids.find((id, i) => ids.indexOf(id) !== i);
  if (duplicate !== undefined) {
    console.error(`duplicate case id: ${duplicate}`);
    return 1;
  }

  const outcomes = run();
  const markdown = report(outcomes);
  const baseline = baselineOf(outcomes);
  const baselineJson = `${JSON.stringify(baseline, null, 2)}\n`;

  if (process.argv.includes("--write")) {
    writeFileSync(RESULTS_PATH, markdown);
    writeFileSync(BASELINE_PATH, baselineJson);
    console.log(markdown);
    console.log("wrote evals/gate-results.md and evals/gate-baseline.json");
    return 0;
  }

  const committedRaw = readOrEmpty(BASELINE_PATH);
  if (committedRaw === "") {
    console.error("evals/gate-baseline.json is missing — run: npm run eval:gate -- --write");
    return 1;
  }
  const committed = JSON.parse(committedRaw) as Baseline;
  const problems: string[] = [];
  for (const o of outcomes) {
    const id = o.gateCase.id;
    const wasMiss = Object.hasOwn(committed.knownMisses, id);
    const isMiss = o.got !== o.gateCase.expected;
    if (isMiss && !wasMiss) {
      problems.push(`REGRESSION ${id}: expected ${o.gateCase.expected}, got ${o.got} (${o.gateCase.why})`);
    } else if (!isMiss && wasMiss) {
      problems.push(`FIXED ${id}: now ${o.got} as expected — the published numbers are stale`);
    } else if (isMiss && committed.knownMisses[id] !== o.got) {
      problems.push(`CHANGED ${id}: still wrong, but now ${o.got} (was ${committed.knownMisses[id]})`);
    }
  }
  for (const id of Object.keys(committed.knownMisses)) {
    if (!ids.includes(id)) problems.push(`STALE baseline entry ${id}: no such case`);
  }
  if (problems.length === 0 && readOrEmpty(RESULTS_PATH) !== markdown) {
    problems.push("evals/gate-results.md does not match the current run");
  }

  const misses = Object.keys(baseline.knownMisses).length;
  if (problems.length > 0) {
    for (const p of problems) console.error(p);
    console.error("\nIf the change is intended: npm run eval:gate -- --write, then commit.");
    return 1;
  }
  console.log(
    `gate eval: ${outcomes.length - misses}/${outcomes.length} correct, ${misses} known misses — matches evals/gate-results.md`,
  );
  return 0;
}

process.exit(main());
